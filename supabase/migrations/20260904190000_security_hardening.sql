create table if not exists public.speech_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  character_count integer not null check (character_count between 1 and 300),
  requested_at timestamptz not null default now()
);

create index if not exists speech_usage_user_requested_idx
  on public.speech_usage (user_id, requested_at desc);

alter table public.speech_usage enable row level security;

create or replace function public.consume_speech_quota(p_character_count integer)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_recent_requests integer;
  v_daily_characters integer;
begin
  if v_user_id is null or p_character_count not between 1 and 300 then
    return false;
  end if;

  perform 1 from public.profiles where id = v_user_id for update;

  delete from public.speech_usage
  where user_id = v_user_id
    and requested_at < now() - interval '7 days';

  select count(*) into v_recent_requests
  from public.speech_usage
  where user_id = v_user_id
    and requested_at >= now() - interval '5 minutes';

  select coalesce(sum(character_count), 0) into v_daily_characters
  from public.speech_usage
  where user_id = v_user_id
    and requested_at >= now() - interval '24 hours';

  if v_recent_requests >= 12 or v_daily_characters + p_character_count > 1500 then
    return false;
  end if;

  insert into public.speech_usage (user_id, character_count)
  values (v_user_id, p_character_count);

  return true;
end;
$$;

revoke all on function public.consume_speech_quota(integer) from public;
grant execute on function public.consume_speech_quota(integer) to authenticated;

