create or replace function public.start_lesson_attempt(p_lesson_id uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_total integer;
  v_attempt_id uuid;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  select count(*) into v_total
  from public.lesson_activities
  join public.lessons on lessons.id = lesson_activities.lesson_id
  where lesson_activities.lesson_id = p_lesson_id
    and lessons.is_published;

  if v_total < 1 then
    raise exception 'Lesson is unavailable';
  end if;

  insert into public.lesson_attempts (user_id, lesson_id, total_activities)
  values (v_user_id, p_lesson_id, v_total)
  returning id into v_attempt_id;

  return v_attempt_id;
end;
$$;

revoke all on function public.start_lesson_attempt(uuid) from public;
grant execute on function public.start_lesson_attempt(uuid) to authenticated;

create or replace function public.submit_lesson_response(
  p_attempt_id uuid,
  p_activity_id uuid,
  p_answer text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_correct_answer text;
  v_is_correct boolean;
begin
  if v_user_id is null or p_answer is null then
    raise exception 'Invalid lesson response';
  end if;

  select lesson_activities.correct_answer into v_correct_answer
  from public.lesson_attempts
  join public.lesson_activities
    on lesson_activities.lesson_id = lesson_attempts.lesson_id
  where lesson_attempts.id = p_attempt_id
    and lesson_attempts.user_id = v_user_id
    and lesson_attempts.status = 'in_progress'
    and lesson_activities.id = p_activity_id;

  if v_correct_answer is null then
    raise exception 'Invalid lesson activity';
  end if;

  v_is_correct := p_answer = v_correct_answer;

  insert into public.lesson_responses (
    attempt_id, activity_id, user_id, answer, is_correct
  ) values (
    p_attempt_id, p_activity_id, v_user_id, p_answer, v_is_correct
  )
  on conflict (attempt_id, activity_id) do update
    set answer = excluded.answer,
        is_correct = excluded.is_correct,
        answered_at = now()
    where lesson_responses.user_id = v_user_id;

  return v_is_correct;
end;
$$;

revoke all on function public.submit_lesson_response(uuid, uuid, text) from public;
grant execute on function public.submit_lesson_response(uuid, uuid, text) to authenticated;

create or replace function public.complete_lesson_attempt(p_attempt_id uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_score integer;
  v_total integer;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  select total_activities into v_total
  from public.lesson_attempts
  where id = p_attempt_id
    and user_id = v_user_id
    and status = 'in_progress'
  for update;

  if v_total is null then
    raise exception 'Invalid lesson attempt';
  end if;

  select count(*) filter (where is_correct) into v_score
  from public.lesson_responses
  where attempt_id = p_attempt_id
    and user_id = v_user_id;

  update public.lesson_attempts
  set status = 'completed', score = v_score, completed_at = now()
  where id = p_attempt_id and user_id = v_user_id;

  return v_score;
end;
$$;

revoke all on function public.complete_lesson_attempt(uuid) from public;
grant execute on function public.complete_lesson_attempt(uuid) to authenticated;
