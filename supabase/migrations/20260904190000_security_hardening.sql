create or replace function public.complete_level_assessment(
  p_answers integer[],
  p_accepted_level text
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_correct integer[] := array[1, 1, 1, 2, 1, 0, 1, 0];
  v_keys text[] := array[
    'plans_subjunctive',
    'past_narrative',
    'purpose_para',
    'conditional',
    'reported_request',
    'connector',
    'past_hypothesis',
    'nuanced_expression'
  ];
  v_score integer := 0;
  v_recommended_level text;
  v_attempt_id uuid;
  v_index integer;
begin
  if v_user_id is null or array_length(p_answers, 1) is distinct from 8 then
    raise exception 'Invalid assessment submission';
  end if;

  for v_index in 1..8 loop
    if p_answers[v_index] not between 0 and 2 then
      raise exception 'Invalid assessment answer';
    end if;
    if p_answers[v_index] = v_correct[v_index] then
      v_score := v_score + 1;
    end if;
  end loop;

  v_recommended_level := case
    when v_score <= 2 then 'A2'
    when v_score <= 5 then 'B1'
    when v_score <= 7 then 'B2'
    else 'C1'
  end;

  if p_accepted_level is distinct from v_recommended_level then
    raise exception 'Assessment level does not match score';
  end if;

  insert into public.assessment_attempts (
    user_id, status, score, total_points, recommended_level,
    accepted_level, completed_at
  ) values (
    v_user_id, 'completed', v_score, 8, v_recommended_level,
    p_accepted_level, now()
  ) returning id into v_attempt_id;

  for v_index in 1..8 loop
    insert into public.assessment_answers (
      attempt_id, user_id, question_key, selected_answer, is_correct, points
    ) values (
      v_attempt_id,
      v_user_id,
      v_keys[v_index],
      p_answers[v_index]::text,
      p_answers[v_index] = v_correct[v_index],
      case when p_answers[v_index] = v_correct[v_index] then 1 else 0 end
    );
  end loop;

  return v_attempt_id;
end;
$$;

revoke all on function public.complete_level_assessment(integer[], text) from public;
grant execute on function public.complete_level_assessment(integer[], text) to authenticated;

